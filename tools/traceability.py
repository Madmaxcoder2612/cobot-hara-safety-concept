"""Check the HARA data for consistency and generate the report tables.

Reads the four CSV files in ../data, checks that the chain

    hazard -> safety function -> safety requirement -> test case

has no gaps, and writes:

    docs/04-hara-table.md
    docs/05-traceability-matrix.md

Run from the project folder:

    python tools/traceability.py

Exit code 0 means every check passed, 1 means at least one finding.
"""

import csv
import sys
from pathlib import Path

from plr import highest_pl, pl_at_least, required_pl

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"


def load(name):
    with open(DATA / name, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def split_ids(cell):
    return [part.strip() for part in cell.split(";") if part.strip()]


def check(hazards, functions, requirements, tests):
    """Return (findings, plr per hazard, required PL per safety function)."""
    findings = []
    sf_ids = {sf["id"] for sf in functions}
    sr_ids = {sr["id"] for sr in requirements}

    for name, rows in (("hazard", hazards), ("safety function", functions),
                       ("requirement", requirements), ("test case", tests)):
        ids = [row["id"] for row in rows]
        for dup in sorted({i for i in ids if ids.count(i) > 1}):
            findings.append(f"Duplicate {name} id {dup}")

    hazard_plr = {}
    sf_required = {sf_id: [] for sf_id in sf_ids}
    for hz in hazards:
        try:
            plr = required_pl(hz["S"], hz["F"], hz["P"])
        except ValueError as err:
            findings.append(f"{hz['id']}: {err}")
            continue
        linked = split_ids(hz["safety_functions"])
        if linked:
            hazard_plr[hz["id"]] = plr
        elif not (hz["design_measures"] or hz["information_measures"]):
            findings.append(f"{hz['id']}: no risk reduction measure at all")
        for sf_id in linked:
            if sf_id not in sf_ids:
                findings.append(f"{hz['id']}: unknown safety function {sf_id}")
            else:
                sf_required[sf_id].append(plr)

    sf_plr = {}
    for sf in functions:
        needed = sf_required[sf["id"]]
        if not needed:
            findings.append(f"{sf['id']}: not linked to any hazard")
            continue
        sf_plr[sf["id"]] = highest_pl(needed)
        if not pl_at_least(sf["pl_target"], sf_plr[sf["id"]]):
            findings.append(
                f"{sf['id']}: target PL {sf['pl_target']} is below required PL {sf_plr[sf['id']]}"
            )

    covered_sf = set()
    for sr in requirements:
        if sr["safety_function"] == "ALL":
            covered_sf |= sf_ids
        elif sr["safety_function"] not in sf_ids:
            findings.append(f"{sr['id']}: unknown safety function {sr['safety_function']}")
        else:
            covered_sf.add(sr["safety_function"])
    for sf_id in sorted(sf_ids - covered_sf):
        findings.append(f"{sf_id}: has no safety requirement")

    tested = set()
    for tc in tests:
        if tc["requirement"] not in sr_ids:
            findings.append(f"{tc['id']}: unknown requirement {tc['requirement']}")
        tested.add(tc["requirement"])
    for sr_id in sorted(sr_ids - tested):
        findings.append(f"{sr_id}: has no test case")

    return findings, hazard_plr, sf_plr


def cell(text):
    return text.replace("|", "/").strip() or "-"


def write_hara_table(hazards, hazard_plr):
    lines = [
        "# HARA table",
        "",
        "Generated by `tools/traceability.py` from `data/hazards.csv`. Do not edit by hand.",
        "",
        "PLr is shown only where a control safety function is part of the risk reduction.",
        "",
        "| ID | Phase | Hazardous situation | Harm | S | F | P | PLr | Safety functions |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for hz in hazards:
        lines.append(
            f"| {hz['id']} | {cell(hz['phase'])} | {cell(hz['hazardous_situation'])} | "
            f"{cell(hz['harm'])} | {hz['S']} | {hz['F']} | {hz['P']} | "
            f"{hazard_plr.get(hz['id'], '-')} | {cell(hz['safety_functions'].replace(';', ', '))} |"
        )
    lines += ["", "## Rationale and other measures", ""]
    for hz in hazards:
        lines += [
            f"### {hz['id']}: {hz['hazard']}",
            "",
            f"- **Task:** {hz['task']}",
            f"- **Why S/F/P:** {hz['rationale']}",
            f"- **Inherently safe design:** {cell(hz['design_measures'])}",
            f"- **Information for use:** {cell(hz['information_measures'])}",
            "",
        ]
    (DOCS / "04-hara-table.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_matrix(hazards, functions, requirements, tests, sf_plr):
    tests_by_sr = {}
    for tc in tests:
        tests_by_sr.setdefault(tc["requirement"], []).append(tc["id"])
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `tools/traceability.py`. Do not edit by hand.",
        "",
        "| Safety function | Required PL | Target PL | Hazards covered | Requirements | Test cases |",
        "|---|---|---|---|---|---|",
    ]
    for sf in functions:
        hz_ids = [h["id"] for h in hazards if sf["id"] in split_ids(h["safety_functions"])]
        sr_ids = [r["id"] for r in requirements if r["safety_function"] in (sf["id"], "ALL")]
        tc_ids = [tc for sr in sr_ids for tc in tests_by_sr.get(sr, [])]
        lines.append(
            f"| {sf['id']} {sf['name']} | {sf_plr.get(sf['id'], '-')} | {sf['pl_target']} | "
            f"{', '.join(hz_ids)} | {', '.join(sr_ids)} | {', '.join(tc_ids)} |"
        )
    lines += [
        "",
        "## Requirements and their tests",
        "",
        "| Requirement | Safety function | Text | Test | Method |",
        "|---|---|---|---|---|",
    ]
    tests_by_id = {tc["id"]: tc for tc in tests}
    for sr in requirements:
        for tc_id in tests_by_sr.get(sr["id"], ["-"]):
            method = tests_by_id[tc_id]["method"] if tc_id in tests_by_id else "-"
            lines.append(
                f"| {sr['id']} | {sr['safety_function']} | {cell(sr['text'])} | {tc_id} | {method} |"
            )
    lines.append("")
    (DOCS / "05-traceability-matrix.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    hazards = load("hazards.csv")
    functions = load("safety_functions.csv")
    requirements = load("requirements.csv")
    tests = load("test_cases.csv")

    findings, hazard_plr, sf_plr = check(hazards, functions, requirements, tests)

    DOCS.mkdir(exist_ok=True)
    write_hara_table(hazards, hazard_plr)
    write_matrix(hazards, functions, requirements, tests, sf_plr)

    print(f"{len(hazards)} hazards, {len(functions)} safety functions, "
          f"{len(requirements)} requirements, {len(tests)} test cases")
    if findings:
        print(f"{len(findings)} finding(s):")
        for finding in findings:
            print(f"  - {finding}")
        return 1
    print("All traceability checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
